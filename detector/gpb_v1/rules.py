def classify_code(code: str) -> str:

    if code in DELETED_CODES:

        return "DELETED"

    if code in KNOWN_FAKE_CODES:

        return "KNOWN"

    if code in HARD_CODES:

        return "HARD"

    if code in DIAGNOSTIC_CODES:

        return "DIAGNOSTIC"

    if code in _FORENSICS_DIAGNOSTIC:

        return "DIAGNOSTIC"

    return "DIAGNOSTIC"

